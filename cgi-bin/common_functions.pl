#-------------------------------------------------------------------------------
# HTMLエスケープ
#-------------------------------------------------------------------------------
sub html_escape {
    my ($str) = @_;

    $str =~ s/&/&amp;/g;
    $str =~ s/</&lt;/g;
    $str =~ s/>/&gt;/g;
    $str =~ s/"/&quot;/g;

    return $str;
}

#-------------------------------------------------------------------------------
# 自分のIPのチェック
#-------------------------------------------------------------------------------
sub my_ip_check {
    my ($ip) = @_;

    return ($ip eq '133.202.106.174' || $ip eq '49.97.14.169' || $ip eq '49.97.22.186');
}

#-------------------------------------------------------------------------------
# 警戒IPのチェック
#-------------------------------------------------------------------------------
sub alert_ip_check {
    my ($ip) = @_;

    return ($ip eq '18.246.159.3'  || $ip eq '45.156.128.64'   || $ip eq '109.105.209.7' ||
            $ip eq '134.209.84.79' || $ip eq '157.173.122.176' || $ip eq '199.45.154.146');
}

#-------------------------------------------------------------------------------
# 警戒hostnameのチェック
#-------------------------------------------------------------------------------
sub alert_hostname_check {
    my ($hostname) = @_;

    return (($hostname =~ /dataprovider/) > 0 || ($hostname =~ /ahrefs/) > 0);
}

#-------------------------------------------------------------------------------
# 警戒User Agentのチェック
#-------------------------------------------------------------------------------
sub alert_ua_chech {
    my ($ua) = @_;

    return (($ua =~ /Go-http-client/) > 0 || ($ua =~ /Cortex-Xpanse/)      > 0 ||
            ($ua =~ /SaaSBrowserBot/) > 0 || ($ua =~ /CMS-Checker/)        > 0 ||
            ($ua =~ /2ip bot/)        > 0 || ($ua =~ /Who\.is Bot/)        > 0 ||
            ($ua =~ /GPTBot/)         > 0 || ($ua =~ /rootevidence\.com$/) > 0);
}

package main;

1;
